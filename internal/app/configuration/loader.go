// Package configuration locates, checks and validates the user's files.
package configuration

import (
	"context"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
)

const (
	ModelsFileName     = "models.json"
	StrategiesFileName = "strategies.json"
	MetadataFileName   = "models-metadata.json"
)

// FileReader is implemented by infra/storage. It is read-only on purpose.
type FileReader interface {
	Read(ctx context.Context, path string) ([]byte, error)
	Mode(ctx context.Context, path string) (fs.FileMode, error)
}

// Config is the validated configuration. Either part may be nil.
type Config struct {
	Dir        string
	Models     *ModelsFile
	Strategies *StrategiesFile
	// Unusable maps a routing command to the reason it cannot be used (Q1).
	Unusable map[string]string
}

// Problem is a file-level error with field path and reason (CFG-5).
type Problem struct {
	File   string
	Path   string
	Reason string
}

func (p Problem) String() string {
	return fmt.Sprintf("%s: %s: %s", p.File, p.Path, p.Reason)
}

// Result is what startup shows to the user.
type Result struct {
	Config   Config
	Warnings []string
	Problems []Problem
}

// ResolveDir implements CFG-1.
func ResolveDir() (string, error) {
	if d := os.Getenv("AGENT_FACTORY_HOME"); d != "" {
		return d, nil
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("locating home directory: %w; set AGENT_FACTORY_HOME", err)
	}
	return filepath.Join(home, ".agent-factory"), nil
}

// Load reads and validates the configuration. It never writes and never
// fails on bad user content: problems are reported in the Result.
func Load(ctx context.Context, r FileReader, dir string) (Result, error) {
	res := Result{Config: Config{Dir: dir, Unusable: map[string]string{}}}
	modelsPath := filepath.Join(dir, ModelsFileName)
	stratPath := filepath.Join(dir, StrategiesFileName)
	metaPath := filepath.Join(dir, MetadataFileName)

	modelsData, mErr := r.Read(ctx, modelsPath)
	stratData, sErr := r.Read(ctx, stratPath)
	_, metaErr := r.Read(ctx, metaPath)
	if err := ctx.Err(); err != nil {
		return res, err
	}
	// An unreadable file is a reported problem, not a crash (CFG-5).
	for _, f := range []struct {
		name string
		err  error
	}{{ModelsFileName, mErr}, {StrategiesFileName, sErr}, {MetadataFileName, metaErr}} {
		if f.err != nil && !errors.Is(f.err, fs.ErrNotExist) {
			res.Problems = append(res.Problems, Problem{File: f.name, Path: "$", Reason: f.err.Error()})
		}
	}

	if errors.Is(mErr, fs.ErrNotExist) {
		res.Warnings = append(res.Warnings, fmt.Sprintf(
			"%s is missing: no model is usable. Create it with your providers and models (see examples/models.json).", modelsPath))
	}
	if errors.Is(sErr, fs.ErrNotExist) {
		res.Warnings = append(res.Warnings, fmt.Sprintf(
			"%s is missing: routing commands are unavailable. Run /suggest, copy a strategy into this file, then run /refresh.", stratPath))
	}
	if errors.Is(metaErr, fs.ErrNotExist) {
		res.Warnings = append(res.Warnings, fmt.Sprintf(
			"%s is missing: it is generated by the tool at startup.", metaPath))
	}

	if mErr == nil {
		var m ModelsFile
		if !collect(&res, ModelsFileName, decodeStrict(modelsData, &m)) &&
			!collect(&res, ModelsFileName, m.Validate()) {
			res.Config.Models = &m
		}
		if mode, err := r.Mode(ctx, modelsPath); err == nil && mode&0o077 != 0 {
			res.Warnings = append(res.Warnings, fmt.Sprintf(
				"%s has permissions %04o and holds API keys: run chmod 600 %s.", modelsPath, mode, modelsPath))
		}
	}
	if sErr == nil {
		var s StrategiesFile
		if !collect(&res, StrategiesFileName, decodeStrict(stratData, &s)) &&
			!collect(&res, StrategiesFileName, s.Validate()) {
			res.Config.Strategies = &s
		}
	}
	crossCheck(&res)
	return res, nil
}

// collect records errors and reports whether there were any.
func collect(res *Result, file string, errs []FieldError) bool {
	for _, e := range errs {
		res.Problems = append(res.Problems, Problem{File: file, Path: e.Path, Reason: e.Reason})
	}
	return len(errs) > 0
}

// crossCheck marks commands unusable when they name unknown models (Q1).
func crossCheck(res *Result) {
	c := &res.Config
	if c.Strategies == nil || c.Models == nil {
		return
	}
	known := map[string]bool{}
	for _, m := range c.Models.Models {
		known[m.ID] = true
	}
	for _, name := range RoutingCommands {
		a, ok := c.Strategies.Commands[name]
		if !ok || !a.Enabled {
			continue
		}
		for _, id := range a.Models {
			if !known[id] {
				reason := fmt.Sprintf("model %q is not in %s", id, ModelsFileName)
				c.Unusable[name] = reason
				res.Warnings = append(res.Warnings, fmt.Sprintf(
					"%s is unusable: %s. Fix %s or add the model to %s.", name, reason, StrategiesFileName, ModelsFileName))
				break
			}
		}
	}
}
